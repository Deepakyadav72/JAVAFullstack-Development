//Push- remove element at the end

const Name= ["Abhishek","Pal","kajal","Gupta"];
Name.push("Kashish","Gupta");
console.log(Name);


//pop- add element at the end
const Name1= ["Abhishek","Pal","kajal","Gupta"];
Name1.pop();
console.log(Name1);

// Shift - remove one element at the first

const Name3= ["Abhishek","Pal","kajal","Gupta"];
Name3.shift();
console.log(Name3);

// Unshift- Add element at the beggining
const Name4= ["Abhishek","Pal","kajal","Gupta"];
Name4.unshift("Deepak");
console.log(Name4);

